export const getTranslation = (lang, key, replacements = {}) => {
  const dict = translations[lang] || translations.en;
  let text = dict[key] || key;
  Object.keys(replacements).forEach(r => {
    text = text.replace(`{${r}}`, replacements[r]);
  });
  return text;
};
